"""Shared fixtures for the ClauseAnchor test suite.

The multi-page PDF is a real text-layer PDF generated by the committed script;
regenerate it at test time when it is missing so a fresh clone can run the
suite without an extra build step.
"""

from __future__ import annotations

import importlib.util
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
MAKE_FIXTURE = ROOT / "tests" / "fixtures" / "make_multipage_gongbao.py"
MULTIPAGE_PDF = MAKE_FIXTURE.with_name("multipage_gongbao.pdf")


@pytest.fixture(scope="session", autouse=True)
def multipage_pdf() -> Path:
    if not MULTIPAGE_PDF.exists():
        spec = importlib.util.spec_from_file_location(
            "make_multipage_gongbao", MAKE_FIXTURE
        )
        assert spec and spec.loader
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        module.main()
    return MULTIPAGE_PDF
